"""Collect every exp*/obs.json into OBSERVATIONS.md (values for the report tables)."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
o = {d.name[:5]: json.loads((d / 'obs.json').read_text()) for d in sorted(root.glob('exp0*')) if (d / 'obs.json').exists()}
L = ['# Observations (generated by tools/summarise.py from obs.json)\n']

e = o['exp01']; s = e['sampling']
L += ['## Experiment 1', '', 'Table 1.1: fs = %g Hz, T = %g s, N = %d, Δf = %g Hz, Nyquist = %g Hz' % (s['fs'], s['T'], s['N'], s['df'], s['nyquist']), '',
      '| Component | Set (Hz) | Measured (Hz) | Set amplitude | Measured amplitude |', '|---|---|---|---|---|']
for name, (fs_, fm, a, am) in zip(['First', 'Second', 'Third'], e['spectrum']):
    L.append(f'| {name} | {fs_} | {fm:.1f} | {a:.2f} | {am:.2f} |')
L += ['', '| Initial angle (deg) | Period, zero crossings (s) | Period, spectrum (s) | Ratio to T0 |', '|---|---|---|---|']
for a, tz, ts, r in e['period_table']:
    L.append(f'| {a} | {tz:.3f} | {ts:.3f} | {r:.2f} |')
lk = e['leakage']
L += ['', f"Aliased peak = {e['alias_peak_hz']} Hz; T0 = {e['T0']:.4f} s; damping b = {e['dampings']} s⁻¹.",
      f"Leakage, T = 1.7 s (Δf = {lk['df']:.3f} Hz): " + '; '.join(f'{p[0]} Hz → peak {p[1]:.3f} Hz, height {p[3]:.3f}' for p in lk['peaks']), '']

e = o['exp02']
L += ['## Experiment 2', '', f"Machine: {e['cpu']}, Python {e['python']}. First solution (n = 8): {e['first_solution']}. Fundamental solutions: {e['fundamental']}.", '',
      '| n | Solutions | Nodes visited | Backtracking (s) | Generate and test (s) |', '|---|---|---|---|---|']
for r in e['rows']:
    L.append(f"| {r['n']} | {r['solutions']} | {r['nodes']:,} | {r['t_bt']:.4f} | {r['t_gt']:.4f} |")
L.append('')

e = o['exp03']; b, d = e['results']['bfs'], e['results']['dfs']
L += ['## Experiment 3', '', '| Quantity | BFS | DFS |', '|---|---|---|',
      f"| Maze size (rows x cols) | {e['H']} x {e['W']} | {e['H']} x {e['W']} |",
      f"| Open cells | {e['open_cells']} | {e['open_cells']} |",
      f"| Cells expanded | {b['expanded']} | {d['expanded']} |",
      f"| Path length (steps) | {b['path_steps']} | {d['path_steps']} |",
      f"| Max frontier size | {b['max_frontier']} | {d['max_frontier']} |",
      f"| Path validated | {'Yes' if b['valid'] else 'No'} | {'Yes' if d['valid'] else 'No'} |", '']

e = o['exp04']
L += ['## Experiment 4', '', f"Plain hill climbing: {e['successes']}/{e['trials']} = {100*e['p']:.1f}% "
      f"(repeat with other seeds: {e['successes_repeat']}/{e['trials']} = {100*e['successes_repeat']/e['trials']:.1f}%; "
      f"with 100 sideways moves: {e['sideways_successes']}/{e['trials']} = {100*e['sideways_successes']/e['trials']:.1f}%). "
      f"Restarts for 99%: {e['k99']}.", '', '| k | Trials | Measured (%) | Predicted (%) |', '|---|---|---|---|']
for r in e['restarts']:
    L.append(f"| {r['k']} | {r['trials']} | {r['measured']:.1f} | {r['predicted']:.1f} |")
L += ['', f"Landscape: {e['n_local_maxima']} local maxima (incl. global at x = {e['x_global']:.2f}); 1-D climbs reaching global: {100*e['oned_reach_global']:.0f}%.", '']

e = o['exp05']
L += ['## Experiment 5', '', f"Grid {e['grid'][0]} x {e['grid'][1]}, rewards goal/step/pit = {e['rewards'][0]}/{e['rewards'][1]}/{e['rewards'][2]}, "
      f"α = {e['alpha']}, γ = {e['gamma']}, episodes = {e['episodes']}, step cap = {e['cap']}, seed = {e['seed']}.", '',
      '| ε | Mean return last 100 (seed 0) | 5 seeds mean ± SD | Greedy policy optimal? |', '|---|---|---|---|']
for r in e['rows']:
    pc = e['policy_check'][str(r['eps'])]
    L.append(f"| {r['eps']} | {r['mean_last100']:.2f} | {r['seeds_mean']:.2f} ± {r['seeds_sd']:.2f} | {'Yes' if pc['optimal'] else 'No'} ({pc['steps']} steps) |")
L += ['', f"Optimal return from start (value iteration): {e['opt_return']:.2f} in {e['opt_steps']} steps. "
      f"Without step cost: route {e['no_step_cost']['steps']} steps.", '', 'Policy grid (ε = 0.20; # wall, G goal, P pit):', '```'] + e['policy_grid'] + ['```', '']

e = o['exp06']
L += ['## Experiment 6', '', f"Network {e['shape']}, {e['activations']}, loss {e['loss']}, seed {e['seed']}, epochs {e['epochs']}.", '',
      '| Learning rate | Final MSE | Converged? | Epoch MSE < 1e-2 |', '|---|---|---|---|']
for r in e['rows']:
    L.append(f"| {r['lr']} | {r['final_mse']:.2e} | {'Yes' if r['converged'] else 'No'} | {r['epoch_mse_below_1e2']} |")
L += ['', f"Best run lr = {e['best_lr']}; predictions for (0,0),(0,1),(1,0),(1,1): {e['best_pred']}.",
      f"Single linear unit: outputs {e['single_unit']['outputs']}, MSE {e['single_unit']['mse']:.3f}. "
      f"Zero initialisation: outputs {e['zero_init']['outputs']}, MSE {e['zero_init']['mse']:.3f}.", '']
(root / 'OBSERVATIONS.md').write_text('\n'.join(L))
print('\n'.join(L))
